// used to pass messages from event handler to the UI
final messageStreamController = BehaviorSubject<RemoteMessage>();
Future<void> _firebaseMessagingBackgroundHandler(RemoteMessage message) async {
  // showNotification(message);

  if (kDebugMode) {
    print("Handler in main.dart");
    print("Handling a background message: ${message.messageId}");
    print('Message data: ${message.data}');
    print('Message notification: ${message.notification?.title}');
    print('Message notification: ${message.notification?.body}');
  }
}

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );
  FirebaseMessaging.onBackgroundMessage(_firebaseMessagingBackgroundHandler);

  AwesomeNotifications().initialize(
      null,
      [
        NotificationChannel(
          channelGroupKey: 'basic_channel_group',
          channelKey: 'basic_channel',
          channelName: 'Basic notifications',
          channelDescription: 'Notification channel for basic tests',
          defaultColor: GlobalStyle.primaryColor,
          ledColor: Colors.white,
          importance: NotificationImportance.High,
          channelShowBadge: true,
          defaultRingtoneType: DefaultRingtoneType.Notification,
          icon: 'resource://drawable/ic_notification',
          playSound: true,
          enableVibration: true,
          vibrationPattern: Int64List.fromList([1000, 1000, 2000, 1000, 3000]),
        )
      ],
      // Channel groups are only visual and are not required
      channelGroups: [
        NotificationChannelGroup(
          channelGroupKey: 'basic_channel_group',
          channelGroupName: 'Basic group',
        )
      ],
      debug: true);
  AwesomeNotifications().isNotificationAllowed().then((isAllowed) {
    if (!isAllowed) {
      AwesomeNotifications().requestPermissionToSendNotifications();
    }
  });

  final messaging = FirebaseMessaging.instance;

  messaging.setForegroundNotificationPresentationOptions(
    alert: true, // Required to display a heads up notification
    badge: true,
    sound: true,
  );

  String? token = await messaging.getToken();
  log('FCM Token: $token');
  SharedPreferences prefs = await SharedPreferences.getInstance();
  prefs.setString('fcmToken', token!);
  if (kDebugMode) {
    print('Registration Token=$token');
  }

  PhonePePaymentService().phonepeInit();
  final appId = await PhonePePaymentSdk.getPackageSignatureForAndroid();

  log('AppId: $appId');

  // Initialize SharedPreferences
  SharedPreferences sharedPreferences = await SharedPreferences.getInstance();

  // Initialize Firebase Messaging
  FirebaseMessaging firebaseMessaging = FirebaseMessaging.instance;

  // Initialize other dependencies

  LocationService locationService = LocationService();

  // Initialize Providers
  UserProvider userProvider = UserProvider();
  SalesProvider salesProvider = SalesProvider(userProvider);

  // Initialize UserService
  UserService userService = UserService(
    userProvider: userProvider,
    salesProvider: salesProvider,
    sharedPreferences: sharedPreferences,
    firebaseMessaging: firebaseMessaging,
    locationService: locationService,
  );

  runApp(MultiProvider(
    providers: [
      ChangeNotifierProvider(create: (context) => ProductsProvider()),
      ChangeNotifierProvider<UserProvider>.value(value: userProvider),
      ChangeNotifierProvider<SalesProvider>.value(value: salesProvider),
      Provider<UserService>.value(value: userService),
    ],
    child: const MyApp(),
  ));
}
